/**
 * Utility functions for exporting data
 */

/**
 * Converts subnet data to CSV format
 */
export const subnetsToCsv = (
  subnets: Array<{
    subnet: string;
    networkAddress: string;
    broadcastAddress: string;
    firstUsableHost: string;
    lastUsableHost: string;
    hostsCount: number;
  }>,
  originalSubnet: string,
  calculationMethod: 'vlans' | 'mask'
): string => {
  // Create CSV header
  const header = [
    'Index',
    'VLAN/Subnet',
    'Subnet CIDR',
    'Network Address',
    'Subnet Mask',
    'Broadcast Address',
    'First Usable Host',
    'Last Usable Host',
    'Usable Hosts Count'
  ].join(',');
  
  // Create CSV rows
  const rows = subnets.map((subnet, index) => {
    const cidrParts = subnet.subnet.split('/');
    const prefix = cidrParts[1];
    const subnetMask = prefixToSubnetMask(parseInt(prefix, 10));
    
    return [
      index + 1,
      calculationMethod === 'vlans' ? `VLAN ${index + 1}` : `Subnet ${index + 1}`,
      subnet.subnet,
      subnet.networkAddress,
      subnetMask,
      subnet.broadcastAddress,
      subnet.firstUsableHost,
      subnet.lastUsableHost,
      subnet.hostsCount
    ].join(',');
  });
  
  // Add metadata as comment at the top
  const metadata = [
    `# Original Subnet: ${originalSubnet}`,
    `# Calculation Method: ${calculationMethod === 'vlans' ? 'By VLANs' : 'By Subnet Mask'}`,
    `# Generated: ${new Date().toISOString()}`,
    ''
  ].join('\n');
  
  // Combine everything
  return metadata + header + '\n' + rows.join('\n');
};

/**
 * Exports VLAN and subnet data to CSV format
 */
export const vlansAndSubnetsToCsv = (
  subnets: Array<{
    subnet: string;
    networkAddress: string;
    broadcastAddress: string;
    firstUsableHost: string;
    lastUsableHost: string;
    hostsCount: number;
  }>,
  vlanIds: Record<number, number> = {},
  vlanNames: Record<number, string> = {},
  excludedVlans: number[] = []
): string => {
  // Create CSV header
  const header = [
    'Index',
    'VLAN ID',
    'VLAN Name',
    'Subnet CIDR',
    'Network Address',
    'Subnet Mask',
    'Broadcast Address',
    'First Usable Host',
    'Last Usable Host',
    'Usable Hosts Count'
  ].join(',');
  
  // Create CSV rows
  const rows = subnets.map((subnet, index) => {
    const cidrParts = subnet.subnet.split('/');
    const prefix = cidrParts[1];
    const subnetMask = prefixToSubnetMask(parseInt(prefix, 10));
    const vlanId = vlanIds[index] || (index + 1);
    const vlanName = vlanNames[index] || `VLAN-${vlanId}`;
    
    return [
      index + 1,
      vlanId,
      vlanName,
      subnet.subnet,
      subnet.networkAddress,
      subnetMask,
      subnet.broadcastAddress,
      subnet.firstUsableHost,
      subnet.lastUsableHost,
      subnet.hostsCount
    ].join(',');
  });
  
  // Add metadata as comment at the top
  const metadata = [
    `# Network Configuration Export`,
    `# Generated: ${new Date().toISOString()}`,
    excludedVlans.length > 0 ? `# Excluded VLAN IDs: ${excludedVlans.join(', ')}` : '',
    ''
  ].join('\n');
  
  // Combine everything
  return metadata + header + '\n' + rows.join('\n');
};

/**
 * Converts CIDR prefix to subnet mask
 */
export const prefixToSubnetMask = (prefix: number): string => {
  const mask = (0xffffffff << (32 - prefix)) >>> 0;
  return [
    (mask >>> 24) & 255,
    (mask >>> 16) & 255,
    (mask >>> 8) & 255,
    mask & 255
  ].join('.');
};

/**
 * Downloads data as a file
 */
export const downloadFile = (data: string, filename: string, mimeType: string): void => {
  const blob = new Blob([data], { type: mimeType });
  const url = window.URL.createObjectURL(blob);
  const link = document.createElement('a');
  
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  window.URL.revokeObjectURL(url);
};

/**
 * Generates appropriate VLAN IDs considering exclusion list
 */
export const generateVlanIds = (
  startingVlanId: number,
  count: number,
  excludedVlans: number[] = []
): Record<number, number> => {
  const result: Record<number, number> = {};
  let currentVlanId = startingVlanId;
  
  for (let i = 0; i < count; i++) {
    // Skip excluded VLANs
    while (excludedVlans.includes(currentVlanId)) {
      currentVlanId++;
    }
    
    result[i] = currentVlanId;
    currentVlanId++;
  }
  
  return result;
};

/**
 * Generates Extreme Networks VOSS configuration for interfaces and VRRP
 */
export const generateVOSSConfig = (
  subnets: Array<{
    subnet: string;
    networkAddress: string;
    broadcastAddress: string;
    firstUsableHost: string;
    lastUsableHost: string;
    hostsCount: number;
  }>,
  vlanIds: Record<number, number>,
  useFirstIps: boolean,
  vlanNames: Record<number, string> = {},
  excludedVlans: number[] = []
): string => {
  let config = "! Extreme Networks VOSS Configuration\n";
  config += "! Generated by SubnetSlicer\n";
  config += `! Generated on: ${new Date().toISOString()}\n\n`;

  // Add global configuration
  config += "enable\nconfigure terminal\n\n";
  
  // Add excluded VLANs info if any
  if (excludedVlans.length > 0) {
    config += `! Excluded VLAN IDs: ${excludedVlans.join(', ')}\n\n`;
  }
  
  // Process each subnet
  subnets.forEach((subnet, index) => {
    const vlanId = vlanIds[index] || (index + 1);
    const vlanName = vlanNames[index] || `VLAN-${vlanId}`;
    const subnetCidr = subnet.subnet.split('/')[1];
    const ipBase = subnet.networkAddress.split('.');
    
    // Get the three IPs to use (either first or last three usable)
    let routerIps: string[] = [];
    if (useFirstIps) {
      // Use first three IPs in subnet
      const firstOctet = parseInt(ipBase[3], 10);
      routerIps = [
        `${ipBase[0]}.${ipBase[1]}.${ipBase[2]}.${firstOctet + 1}`,
        `${ipBase[0]}.${ipBase[1]}.${ipBase[2]}.${firstOctet + 2}`,
        `${ipBase[0]}.${ipBase[1]}.${ipBase[2]}.${firstOctet + 3}`
      ];
    } else {
      // Use last three IPs in subnet
      const broadcastParts = subnet.broadcastAddress.split('.');
      const lastOctet = parseInt(broadcastParts[3], 10);
      routerIps = [
        `${broadcastParts[0]}.${broadcastParts[1]}.${broadcastParts[2]}.${lastOctet - 3}`,
        `${broadcastParts[0]}.${broadcastParts[1]}.${broadcastParts[2]}.${lastOctet - 2}`,
        `${broadcastParts[0]}.${broadcastParts[1]}.${broadcastParts[2]}.${lastOctet - 1}`
      ];
    }
    
    // Virtual IP will be the first of the three IPs
    const virtualIp = routerIps[0];
    
    // VLAN configuration
    config += `! VLAN ${vlanId} Configuration (${vlanName})\n`;
    config += `vlan create ${vlanId} name "${vlanName}"\n`;
    config += `vlan members add ${vlanId} 1/1-1/48\n\n`;
    
    // Router interfaces configuration
    config += `! Router interfaces for VLAN ${vlanId} (${vlanName})\n`;
    config += `interface vlan ${vlanId}\n`;
    config += `ip address ${routerIps[1]}/${subnetCidr}\n`;
    config += `exit\n\n`;
    
    // VRRP configuration
    config += `! VRRP configuration for VLAN ${vlanId} (${vlanName})\n`;
    config += `router vrrp enable\n`;
    config += `interface vlan ${vlanId}\n`;
    config += `ip vrrp address ${vlanId} ${virtualIp}\n`;
    config += `ip vrrp ${vlanId} enable\n`;
    config += `ip vrrp ${vlanId} backup-master enable\n`;
    config += `ip vrrp ${vlanId} priority 200\n`;
    config += `exit\n\n`;
  });
  
  config += "! End of configuration\n";
  config += "end\nwrite memory\n";
  
  return config;
};
